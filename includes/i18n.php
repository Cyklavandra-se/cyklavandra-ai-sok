/** WPML-koder → våra språknycklar. */
function cvai_norm_lang( $lang ) {
	$lang = strtolower( (string) $lang );
	$map  = array(
		'no'    => 'nb',
		'nn'    => 'nb',
		'nb'    => 'nb',
		'se'    => 'sv',
		'en-gb' => 'en',
		'en-us' => 'en',
		'de-ch' => 'de',
		'de-at' => 'de',
		'pt-pt' => 'pt',
		'pt-br' => 'pt',
	);
	if ( isset( $map[ $lang ] ) ) {
		return $map[ $lang ];
	}
	return substr( $lang, 0, 2 );
}

function cvai_lang_name( $lang ) {
	$names = array(
		'sv' => 'svenska',
		'nb' => 'norska (bokmål)',
		'da' => 'danska',
		'en' => 'engelska',
		'de' => 'tyska',
		'fi' => 'finska',
		'nl' => 'nederländska',
		'fr' => 'franska',
		'es' => 'spanska',
		'it' => 'italienska',
		'pt' => 'portugisiska',
		'pl' => 'polska',
	);
	$k = cvai_norm_lang( $lang );
	return $names[ $k ] ?? $lang;
}

